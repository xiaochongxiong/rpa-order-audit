def write_sheet(headers, rows, path, highlight=None):
    wb = Workbook()
    ws = wb.active
    ws.title = "Sheet1"
    ws.append(headers)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="DDEBF7")
    for row in rows:
        ws.append(row)
    widths = {1: 12, 2: 10, 3: 10, 4: 14, 5: 10, 6: 10, 7: 10, 8: 22,
              9: 14, 10: 8, 11: 10, 12: 10, 13: 12, 14: 12, 15: 12,
              16: 14, 17: 12, 18: 16}
    for i, h in enumerate(headers, 1):
        ws.column_dimensions[chr(64 + i) if i <= 26 else "A"].width = widths.get(i, 14)
    wb.save(path)
    print(f"生成 {path.name}: {len(rows)} 行")


